import { test, expect } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { loginAsAdmin, openFirstProfile } from './helpers.js'

const PNG_1PX = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==',
  'base64',
)

/**
 * The application currently creates the development-goals PDF through the
 * browser's print pipeline. This test deliberately exercises Chromium's real
 * PDF renderer instead of treating print CSS as a unit-test-only concern.
 *
 * It protects the shipped checklist output. The planned media-evidence
 * appendix has its own acceptance requirements in deploy/FOLLOW_UPS.md and
 * must extend this test when that feature is implemented.
 */
test.describe('Development-goals PDF', () => {
  test('renders a safe, bounded, print-ready stage checklist', async ({ page, browserName }, testInfo) => {
    test.skip(browserName !== 'chromium', 'Playwright page.pdf() is Chromium-only.')

    await loginAsAdmin(page)
    await openFirstProfile(page)
    const profileId = page.url().match(/\/profile\/(\d+)/)?.[1]
    expect(profileId, 'profile id is present in the profile URL').toBeTruthy()

    // Keep the test deterministic without assuming that this band was seeded
    // in the reusable E2E profile. Seeding is idempotent.
    const seeded = await page.request.post(
      `/api/profiles/${profileId}/child-development/12mo/seed`,
    )
    expect(seeded.ok(), `could not seed PDF test data: ${seeded.status()}`).toBeTruthy()

    await page.getByRole('button', { name: /Early Growth Markers/ }).click()
    await page.getByRole('button', { name: /~12 Months/ }).first().click()
    await expect(page.getByRole('heading', { name: '~12 Months' })).toBeVisible()
    await expect(page.getByText('peekaboo or pat-a-cake', { exact: false })).toBeVisible()

    // The browser filename is generated by printSheet() from date, time, age
    // band, and the full child name. Capture it without opening a print dialog.
    await page.evaluate(() => {
      window.__lpPrintedTitle = null
      window.print = () => { window.__lpPrintedTitle = document.title }
    })
    await page.getByRole('button', { name: /Print stage sheet/ }).click()
    const printTitle = await page.evaluate(() => window.__lpPrintedTitle)
    expect(printTitle).toMatch(/^\d{8}-\d{6}-12mo-.+$/)

    await page.emulateMedia({ media: 'print' })

    // The paper header is the family record: it must identify the child and
    // stage, carry a print date, and preserve the meaning of every status.
    const printHeader = page.locator('.cd-print-header')
    await expect(printHeader).toBeVisible()
    await expect(printHeader).toContainText('Development Checklist')
    await expect(printHeader).toContainText('Printed')
    await expect(printHeader).toContainText('Legend:')
    for (const mark of ['not yet', 'emerging', 'doing']) {
      await expect(printHeader.getByText(mark, { exact: true })).toBeVisible()
    }

    // Interactive controls and private authoring affordances must not become
    // child data in a saved/exported PDF.
    const printOnlyHidden = await page.locator('.cd-no-print').evaluateAll((nodes) =>
      nodes.every((node) => getComputedStyle(node).display === 'none'),
    )
    expect(printOnlyHidden).toBeTruthy()

    // A printout may never contain a presigned object URL, public S3 URL, or
    // other media URL. The future evidence appendix must use authenticated app
    // deep links instead; this baseline catches an accidental URL regression.
    const printableMarkup = await page.locator('body').innerHTML()
    expect(printableMarkup).not.toMatch(/amazonaws\.com|X-Amz-Signature|X-Amz-Credential/i)

    const pdf = await page.pdf({
      format: 'Letter',
      printBackground: true,
      preferCSSPageSize: true,
    })
    const pdfPath = testInfo.outputPath('development-goals-stage-sheet.pdf')
    await writeFile(pdfPath, pdf)
    await testInfo.attach('development-goals-stage-sheet.pdf', {
      path: pdfPath,
      contentType: 'application/pdf',
    })

    expect(pdf.subarray(0, 5).toString(), 'browser produced a PDF').toBe('%PDF-')
    // This is intentionally well below typical email/share limits and leaves
    // room for the future, explicitly bounded evidence appendix.
    expect(pdf.byteLength, 'checklist PDF stays lightweight').toBeLessThan(2 * 1024 * 1024)
  })

  test('renders bounded faux photo and video evidence cards, never playable media', async ({ page, browserName }, testInfo) => {
    test.skip(browserName !== 'chromium', 'Playwright page.pdf() is Chromium-only.')

    await loginAsAdmin(page)
    await openFirstProfile(page)
    const profileId = page.url().match(/\/profile\/(\d+)/)?.[1]
    expect(profileId).toBeTruthy()
    const seeded = await page.request.post(`/api/profiles/${profileId}/child-development/12mo/seed`)
    expect(seeded.ok()).toBeTruthy()
    const group = await (await page.request.get(`/api/profiles/${profileId}/child-development/12mo`)).json()
    const objective = Object.values(group.objectives).flat()[0]
    expect(objective?.id).toBeTruthy()

    const uploads = [
      ['pdf-photo-one.png', 'image/png', Buffer.concat([PNG_1PX, Buffer.from('one')])],
      ['pdf-photo-two.png', 'image/png', Buffer.concat([PNG_1PX, Buffer.from('two')])],
      ['pdf-photo-omitted.png', 'image/png', Buffer.concat([PNG_1PX, Buffer.from('three')])],
      ['pdf-video.mp4', 'video/mp4', Buffer.from('0000001866747970', 'hex')],
    ]
    const media = []
    try {
      for (const [name, mimeType, buffer] of uploads) {
        const response = await page.request.post(`/api/profiles/${profileId}/gallery/`, {
          multipart: { files: { name, mimeType, buffer } },
        })
        expect(response.ok(), `could not upload ${name}: ${response.status()}`).toBeTruthy()
        const [uploaded] = await response.json()
        media.push(uploaded)
        const linked = await page.request.post(`/api/profiles/${profileId}/gallery/${uploaded.id}/objective-links`, {
          data: { objective_id: objective.id },
        })
        expect(linked.ok()).toBeTruthy()
      }

      for (const item of media.slice(0, 2)) {
        const selected = await page.request.put(
          `/api/profiles/${profileId}/gallery/${item.id}/objective-links/${objective.id}/print-evidence`,
          { data: { featured_for_print: true } },
        )
        expect(selected.ok()).toBeTruthy()
      }
      const video = media[3]
      const selectedVideo = await page.request.put(
        `/api/profiles/${profileId}/gallery/${video.id}/objective-links/${objective.id}/print-evidence`,
        { data: { featured_for_print: true, cover_media_id: media[0].id } },
      )
      expect(selectedVideo.ok()).toBeTruthy()

      await page.getByRole('button', { name: /Early Growth Markers/ }).click()
      await page.getByRole('button', { name: /~12 Months/ }).first().click()
      await expect(page.getByRole('heading', { name: '~12 Months' })).toBeVisible()
      await expect(page.getByRole('heading', { name: 'Evidence appendix' })).toBeVisible()
      await expect(page.locator('.cd-evidence-card')).toHaveCount(1)
      await expect(page.locator('.cd-evidence-image')).toHaveCount(3)
      await expect(page.getByText('Video evidence: pdf-video.mp4')).toBeVisible()
      await expect(page.getByText('1 additional linked item omitted')).toBeVisible()

      await page.emulateMedia({ media: 'print' })
      expect(await page.locator('.cd-evidence-appendix video').count()).toBe(0)
      const printableMarkup = await page.locator('.cd-evidence-appendix').innerHTML()
      expect(printableMarkup).not.toMatch(/amazonaws\.com|X-Amz-Signature|X-Amz-Credential/i)
      expect(printableMarkup).toContain(`/api/profiles/${profileId}/gallery/`)

      const pdf = await page.pdf({ format: 'Letter', printBackground: true, preferCSSPageSize: true })
      const pdfPath = testInfo.outputPath('development-goals-evidence-appendix.pdf')
      await writeFile(pdfPath, pdf)
      await testInfo.attach('development-goals-evidence-appendix.pdf', { path: pdfPath, contentType: 'application/pdf' })
      expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
      expect(pdf.byteLength, 'bounded faux evidence PDF').toBeLessThan(2 * 1024 * 1024)
    } finally {
      await Promise.all(media.map((item) => page.request.delete(`/api/profiles/${profileId}/gallery/${item.id}`)))
    }
  })
})
